// Everything that is generated FOR the sandbox (never copied from the original): wp-config.php with fresh salts and random database
// credentials, the must-use plugin that switches mail and outbound HTTP off, the SQL that anonymises a database, and the check for
// payment gateways in live mode. Pure functions: they return text, they run nothing.

const crypto = require('crypto');

const SALT_KEYS = ['AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT'];
const SALT_CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!#%&()*+,-./:;<=>?@[]^_{|}~';
function salt(len = 64) { const b = crypto.randomBytes(len); let s = ''; for (let i = 0; i < len; i++) s += SALT_CHARS[b[i] % SALT_CHARS.length]; return s; }
const phpStr = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// url = http://127.0.0.1:PORT (known only after the container has a port; the file is rewritten then)
function wpConfig({ creds, prefix = 'wp_' }) {
    if (!/^[A-Za-z0-9_]+$/.test(prefix)) throw new Error('unsafe table prefix');
    const salts = SALT_KEYS.map(k => `define( ${phpStr(k)}, ${phpStr(salt())} );`).join('\n');
    return `<?php
/** Generated by Plugin Guard for a throwaway sandbox. Not the original site's wp-config.php: nothing in it comes from the original. */
define( 'DB_NAME', ${phpStr(creds.name)} );
define( 'DB_USER', ${phpStr(creds.user)} );
define( 'DB_PASSWORD', ${phpStr(creds.pass)} );
define( 'DB_HOST', 'db:3306' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
${salts}
$table_prefix = ${phpStr(prefix)};

/* the address is only known once Docker has chosen the port; Plugin Guard writes it to this file, so this file never has to change */
$pg_url = trim( (string) @file_get_contents( '/var/log/pg/url.txt' ) );
if ( '' === $pg_url ) { $pg_url = 'http://127.0.0.1'; }
define( 'WP_HOME', $pg_url );
define( 'WP_SITEURL', $pg_url );
define( 'WP_ENVIRONMENT_TYPE', 'local' );

/* no traffic out, no mail, no cron, no updates */
define( 'WP_HTTP_BLOCK_EXTERNAL', true );   // no WP_ACCESSIBLE_HOSTS: nothing is allowed
define( 'DISABLE_WP_CRON', true );
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_AUTO_UPDATE_CORE', false );
define( 'DISALLOW_FILE_MODS', true );       // no plugin or theme can be installed or edited from inside the sandbox

/* errors go to a file we can read, never to the page */
define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', '/var/log/pg/debug.log' );
define( 'WP_DEBUG_DISPLAY', false );
@ini_set( 'display_errors', '0' );

if ( ! defined( 'ABSPATH' ) ) { define( 'ABSPATH', __DIR__ . '/' ); }
require_once ABSPATH . 'wp-settings.php';
`;
}

// Written into the sandbox copy's mu-plugins. Counts what it blocks, in files the tests can read.
const MU_PLUGIN = `<?php
/**
 * Plugin Name: Plugin Guard sandbox guard
 * Description: Switches off outgoing mail and outgoing HTTP in the throwaway sandbox, and records every attempt in /var/log/pg.
 */
if ( ! defined( 'ABSPATH' ) ) { exit; }
function pg_sandbox_log( $file, $line ) { @file_put_contents( '/var/log/pg/' . $file, $line . "\\n", FILE_APPEND ); }
// Mail: report success so the code carries on, send nothing.
add_filter( 'pre_wp_mail', function ( $return, $atts ) {
	pg_sandbox_log( 'blocked-mail.log', wp_json_encode( array( 'to' => is_array( $atts['to'] ) ? implode( ',', $atts['to'] ) : (string) $atts['to'], 'subject' => (string) $atts['subject'] ) ) );
	return true;
}, 0, 2 );
// HTTP made through WordPress's HTTP API (wp_remote_get, wp_remote_post, ...): refuse everything. Requests to the sandbox itself are not needed either.
add_filter( 'pre_http_request', function ( $pre, $args, $url ) {
	pg_sandbox_log( 'blocked-http.log', wp_json_encode( array( 'method' => isset( $args['method'] ) ? $args['method'] : 'GET', 'url' => preg_replace( '/[?#].*$/', '', (string) $url ) ) ) );
	return new WP_Error( 'pg_sandbox_blocked', 'Outgoing HTTP is switched off in the Plugin Guard sandbox.' );
}, 0, 3 );
add_filter( 'pre_option_blog_public', '__return_zero' );
`;

