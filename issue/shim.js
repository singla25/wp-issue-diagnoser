// Compatibility shims: a small must-use plugin the owner drops into wp-content/mu-plugins/ on a copy or staging site. Plugin Guard only WRITES
// the file into the issue folder (result/patches/shims/); it never places it on a site. Only values that pass a strict whitelist are written
// into the PHP (text from the site is data, never code), and every shim is checked with `php -l`.
// Implemented: hook-priority (make a remove_action / remove_filter effective by using the priority the callback was added with).

const fs = require('fs');
const path = require('path');
const phpast = require('./phpast');

const NAME = /^[A-Za-z0-9_\\:.\/-]{1,120}$/;
const q = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function hookPriority(obs) {
    if (obs.type !== 'remove-wrong-priority') return null;
    const { hook, callback, added_priority: p } = obs;
    if (!hook || !callback || !NAME.test(hook) || !NAME.test(callback) || !Number.isInteger(p)) return { skipped: 'the hook name, the callback, or its priority is not a plain value this generator may write into PHP' };
    if (/::/.test(callback)) return { skipped: 'static-method callbacks are not handled by this shim' };
    const slug = `pg-shim-${hook.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase()}-${callback.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase()}`.slice(0, 80);
    const php = `<?php
/**
 * Plugin Name: Plugin Guard shim: ${slug}
 * Description: Removes ${callback}() from "${hook}" at priority ${p}, the priority it was added with. Generated by Plugin Guard; review before use.
 */
defined( 'ABSPATH' ) || exit;

add_action( 'wp_loaded', function () {
	// A removal only works when it names the priority the callback was added with. ${((obs.evidence || []).find(e => e.role === 'removes') || {}).component || 'The other component'} asks for priority ${obs.removed_priority === null ? 10 : obs.removed_priority}.
	$tag = ${q(hook)};
	$callback = ${q(callback)};
	if ( has_filter( $tag, $callback ) === ${p} ) {
		remove_filter( $tag, $callback, ${p} );
	}
}, 999 );
`;
    return { file: `${slug}.php`, php, summary: `mu-plugin: remove ${callback}() from "${hook}" at priority ${p}`, why: `${callback}() is added to "${hook}" at priority ${p}, but the removal asks for ${obs.removed_priority === null ? 10 : obs.removed_priority}, so it never matches. This shim performs the removal that was intended, after all plugins have loaded.` };
}


// Two components add a callback to the same hook at the same priority, so PHP runs them in load order. Which of the two must run first depends on
// what the callbacks DO, and that is not something this tool can read. So BOTH orders are produced as candidates; only the sandbox can say which
// one makes the symptom disappear (verify-fixes.js marks it "verified in sandbox", the other one stays "tested, did not help").
// A candidate moves ONE callback one priority later at wp_loaded (the accepted-argument count is read from WordPress's own table, not guessed).
function hookOrder(edge) {
    if (!edge || edge.type !== 'hook-same-priority' || !Number.isInteger(edge.priority)) return [];
    const ev = edge.evidence || [];
    if (ev.length !== 2 || !NAME.test(edge.hook || '')) return [{ skipped: 'the hook name is not a plain value this generator may write into PHP' }];
    const cbs = ev.map(e => e.callback);
    if (cbs.some(c => !c || !NAME.test(c) || /::/.test(c) || ['closure', 'method', 'static', 'dynamic', 'unknown'].includes(c))) return [{ skipped: 'at least one callback is not a plain function name (closures and methods cannot be moved by name)' }];
    if (cbs[0] === cbs[1]) return [{ skipped: 'both components use the same callback name' }];
    const out = [];
    for (const [move, other] of [[0, 1], [1, 0]]) {
        const cb = cbs[move], after = cbs[other];
        const slug = `pg-order-${edge.hook.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}-${cb.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}-after-${after.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}`.slice(0, 100);
        const p = edge.priority;
        const php = `<?php
/**
 * Plugin Name: Plugin Guard shim: ${slug}
 * Description: Runs ${cb}() on "${edge.hook}" after ${after}() instead of at the same priority (${p}). Generated by Plugin Guard; one of two candidates, verify before use.
 */
defined( 'ABSPATH' ) || exit;

add_action( 'wp_loaded', function () {
	global $wp_filter;
	$tag = ${q(edge.hook)};
	$callback = ${q(cb)};
	if ( ! isset( $wp_filter[ $tag ] ) || ! isset( $wp_filter[ $tag ]->callbacks[ ${p} ][ $callback ] ) ) {
		return;
	}
	$accepted = (int) $wp_filter[ $tag ]->callbacks[ ${p} ][ $callback ]['accepted_args'];
	remove_filter( $tag, $callback, ${p} );
	add_filter( $tag, $callback, ${p + 1}, $accepted );
}, 999 );
`;
        out.push({ file: `${slug}.php`, php, candidate: `${cb} after ${after}`, summary: `mu-plugin (candidate): run ${cb}() after ${after}() on "${edge.hook}"`, why: `${ev[0].component} and ${ev[1].component} both add a callback to "${edge.hook}" at priority ${p}, so the order is just the order the plugins load. This candidate moves ${cb}() one priority later. The opposite order is a second candidate: Plugin Guard cannot tell from the code which one is right, only a test in the sandbox can.` });
    }
    return out;
}

function lint(s, workDir) {
    let l = null;
    if (workDir) { const f = path.join(workDir, 'shim-test', s.file); fs.mkdirSync(path.dirname(f), { recursive: true, mode: 0o700 }); fs.writeFileSync(f, s.php, { mode: 0o600 }); l = phpast.phpLint(f); }
    const facts = phpast.analyse(s.php, s.file);
    const v = [{ id: 'php-l', status: l === null ? 'NOT_RUN' : l.ok ? 'PASSED' : 'FAILED', reason: l === null ? 'php is not installed' : l.ok ? 'no syntax error' : l.message }, { id: 'parses', status: facts.parsed ? 'PASSED' : 'FAILED', reason: facts.parsed ? 'the PHP scanner parses the shim' : 'the PHP scanner could not parse the shim' }];
    return { ...s, validation: v, ok: v.every(x => x.status !== 'FAILED') };
}
function generateOrder(edge, { workDir } = {}) { return hookOrder(edge).map(s => (s.skipped ? s : lint(s, workDir))); }

function generate(obs, { workDir }) {
    const s = hookPriority(obs);
    if (!s) return { skipped: 'no shim exists for this pattern' };
    if (s.skipped) return s;
    let lint = null;
    if (workDir) { const f = path.join(workDir, 'shim-test', s.file); fs.mkdirSync(path.dirname(f), { recursive: true, mode: 0o700 }); fs.writeFileSync(f, s.php, { mode: 0o600 }); lint = phpast.phpLint(f); }
    const facts = phpast.analyse(s.php, s.file);
    const v = [{ id: 'php-l', status: lint === null ? 'NOT_RUN' : lint.ok ? 'PASSED' : 'FAILED', reason: lint === null ? 'php is not installed' : lint.ok ? 'no syntax error' : lint.message }, { id: 'parses', status: facts.parsed ? 'PASSED' : 'FAILED', reason: facts.parsed ? 'the PHP scanner parses the shim' : 'the PHP scanner could not parse the shim' }];
    return { ...s, validation: v, ok: v.every(x => x.status !== 'FAILED') };
}

module.exports = { generate, generateOrder, hookOrder, q, NAME };
