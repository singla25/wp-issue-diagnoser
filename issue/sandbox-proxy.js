// The front proxy of a sandbox built from a database file (TEST-COPY-SPEC 6c-1). With a dump, the WordPress (web) container is on the INTERNAL
// network only (no route out, no published port), and this proxy is the only container on a network with a route out: it publishes
// 127.0.0.1::80 and passes every request to http://wordpress:80/. It runs Apache from the SAME pinned WordPress image (no new image), as
// www-data (33:33), with no capability, a read-only root file system and a 1 MB tmpfs for its pid file; it reads ONLY this generated config
// (it does not read /etc/apache2/apache2.conf), loads no PHP and serves no files. ProxyRequests Off and no mod_proxy_connect: it is not a
// forward proxy (an absolute URI goes to the sandbox's own WordPress, CONNECT is answered 400).
// conf() is the only source of the config text; checkConf() refuses any text that is not exactly it, and says why. Pure; no Docker needed.

const CONF_PATH = '/etc/pg-proxy/proxy.conf';                       // inside the proxy container
const ENTRYPOINT = ['apache2', '-DFOREGROUND', '-f', CONF_PATH];
const TMPFS = '/run/apache2:size=1m,mode=0700,uid=33,gid=33';
const UPSTREAM = 'http://wordpress:80/';
const MODULES = ['mpm_event', 'authz_core', 'headers', 'reqtimeout', 'proxy', 'proxy_http'];
// what the proxy answers itself when it cannot reach the web container (ErrorDocument applies only to responses the proxy generates,
// never to proxied ones): sandbox.js waits until a request through the proxy no longer starts with this
const OWN_ERROR = 'pg-proxy:';
// the Proxy* directives conf() uses; any other one (ProxyRemote, ProxyPassMatch, ProxySet, <Proxy>, ...) is refused
const PROXY_DIRECTIVES = new Set(['ProxyRequests', 'ProxyPreserveHost', 'ProxyAddHeaders', 'ProxyTimeout', 'ProxyPass', 'ProxyPassReverse']);

function conf() {
    return [
        '# Plugin Guard sandbox front proxy (generated by issue/sandbox-proxy.js; checked by checkConf before anything starts).',
        '# Self-contained: does not read /etc/apache2/apache2.conf, loads no PHP, serves no files. Runs as 33:33 with a read-only root file system.',
        'ServerRoot "/etc/apache2"',
        'ServerName pg-proxy',
        'Listen 80',
        'DefaultRuntimeDir /run/apache2',
        'PidFile /run/apache2/proxy.pid',
        'Mutex file:/run/apache2 default',
        '',
        ...MODULES.map(m => `LoadModule ${m}_module /usr/lib/apache2/modules/mod_${m}.so`),
        '',
        'StartServers 1',
        'ServerLimit 2',
        'ThreadsPerChild 16',
        'MaxRequestWorkers 32',
        '',
        'ErrorLog /dev/stderr',
        'LogLevel warn',
        'LogFormat "%a host=%{Host}i \\"%r\\" %>s %B %Dus" pg',
        'CustomLog /dev/stdout pg',
        '',
        'ServerTokens Prod',
        'ServerSignature Off',
        'TraceEnable Off',
        'Timeout 120',
        'RequestReadTimeout header=20-40,MinRate=500 body=20,MinRate=500',
        'LimitRequestBody 67108864',
        `ErrorDocument 500 "${OWN_ERROR} the web container could not be reached"`,
        `ErrorDocument 502 "${OWN_ERROR} the web container could not be reached"`,
        `ErrorDocument 503 "${OWN_ERROR} the web container could not be reached"`,
        '',
        'ProxyRequests Off',
        'ProxyPreserveHost On',
        'ProxyAddHeaders On',
        'ProxyTimeout 120',
        '# the web container is the compose service "wordpress" on the internal network "back", resolved by Docker\'s embedded DNS',
        `ProxyPass "/" "${UPSTREAM}" retry=0 addressttl=5`,
        `ProxyPassReverse "/" "${UPSTREAM}"`,
        '',
        '<Location "/">',
        '    Require all granted',
        '</Location>',
        ''
    ].join('\n');
}

// -> list of violations (empty = this is the generated config). Each check names what is wrong; the last one refuses any other difference.
function checkConf(text) {
    const v = [], push = m => v.push(`proxy configuration: ${m}`);
    if (typeof text !== 'string' || !text.trim()) return ['proxy configuration: missing or empty'];
    const lines = text.split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith('#'));
    const word = l => (/^<?\/?([A-Za-z]+)/.exec(l) || [])[1] || '';
    if (!lines.some(l => /^ProxyRequests\s+Off$/i.test(l)) || lines.some(l => /^ProxyRequests\s+(?!Off$)/i.test(l))) push('"ProxyRequests Off" is required (the proxy must never act as a forward proxy)');
    const body = lines.join('\n');   // comments are not configuration
    if (/proxy_connect|AllowCONNECT/i.test(body)) push('mod_proxy_connect / AllowCONNECT are refused (CONNECT tunnels)');
    if (/php/i.test(body)) push('no PHP: no PHP module or handler may appear');
    for (const l of lines) {
        const w = word(l);
        if (/^LoadModule$/i.test(w)) {
            const m = /^LoadModule\s+([a-z_]+)_module\s+\/usr\/lib\/apache2\/modules\/mod_([a-z_]+)\.so$/.exec(l);
            if (!m || m[1] !== m[2] || !MODULES.includes(m[1])) push(`module line "${l}" is not one of ${MODULES.join(', ')}`);
        }
        if (/^(Include|IncludeOptional|AddHandler|SetHandler|AddType|Action|ScriptAlias|ScriptAliasMatch|Alias|AliasMatch|DocumentRoot|Rewrite[A-Za-z]*|BalancerMember|User|Group|LoadFile)$/i.test(w)) push(`directive "${w}" is refused (the proxy reads no other file, serves no files and runs no handler)`);
        if (/^Proxy/i.test(w) && !PROXY_DIRECTIVES.has(w)) push(`directive "${w}" is refused (only ${[...PROXY_DIRECTIVES].join(', ')})`);
        if (/^Listen$/i.test(w) && !/^Listen\s+80$/.test(l)) push(`"${l}": the proxy listens on port 80 only`);
    }
    const pass = lines.filter(l => word(l) === 'ProxyPass');
    if (pass.length !== 1 || !new RegExp(`^ProxyPass\\s+"/"\\s+"${UPSTREAM.replace(/[./]/g, '\\$&')}"(\\s+[a-z]+=[0-9A-Za-z]+)*$`).test(pass[0] || '')) push(`exactly one ProxyPass, from "/" to ${UPSTREAM}, is allowed (found ${pass.length})`);
    for (const l of lines.filter(x => word(x) === 'ProxyPassReverse')) if (!l.endsWith(`"${UPSTREAM}"`)) push(`"${l}" must point at ${UPSTREAM}`);
    if (text !== conf()) push('the text is not the configuration Plugin Guard generates (issue/sandbox-proxy.js conf())');
    return v;
}

module.exports = { conf, checkConf, CONF_PATH, ENTRYPOINT, TMPFS, UPSTREAM, MODULES, OWN_ERROR, PROXY_DIRECTIVES };
