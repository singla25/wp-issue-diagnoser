#!/usr/bin/env node
// `npm run guard:knowledge-review`: writes KNOWLEDGE-REVIEW.md, one section per data/known-conflicts.json entry, so a person can check the
// knowledge base against its sources without reading JSON: the claim, the source URL, the excerpt that supports it, and anything the entry
// says that no source states (beyond_sources). Offline and deterministic: it only reads data/known-conflicts.json,
// data/feature-taxonomy.json and data/knowledge-verification.json (the record written by guard:verify-knowledge).
//   node scripts/knowledge-review.js            write KNOWLEDGE-REVIEW.md
//   node scripts/knowledge-review.js --check    exit 1 if the file on disk is not what the data would produce (stale)

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'KNOWLEDGE-REVIEW.md');
const load = f => JSON.parse(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8'));
const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const quote = s => String(s ?? '').replace(/\s+/g, ' ').trim();

function render() {
    const kb = load('known-conflicts.json'), tax = load('feature-taxonomy.json'), v = load('knowledge-verification.json');
    const L = [];
    const entries = kb.entries;
    L.push('# Knowledge-base review', '',
        'For a person to check `data/known-conflicts.json` against the pages it cites. Generated by `npm run guard:knowledge-review` from the data files and from `data/knowledge-verification.json`; do not edit by hand (a test fails if this file is out of date).', '',
        `**Sources were fetched on ${v.fetched_at}.** "Found" means the phrase appears in the text of the page after tags were removed. That shows the page was read and mentions the phrase; it does not prove the page supports the sentence the entry writes. The excerpts below are the evidence for that judgement. Tick each box when you agree.`, '',
        '**What each field is:**',
        '- *Claim* = the entry\'s `causes` text: what the entry says can happen.',
        '- *Change* = the entry\'s `change` text: a recommendation by this tool, not a statement of the source.',
        '- *Beyond the sources* = a part of the claim that no cited page states (the tool\'s own reasoning). It is shown separately so it is not mistaken for something documented.',
        '- *When it fires* = the detector and its parameters, so you can see what a "hit" means on a real site.', '',
        '## Summary', '', '| Entry | Verified | Family | Fires for symptoms | Sources | Claims found | Beyond sources |', '|---|---|---|---|---|---|---|');
    for (const e of entries) {
        const r = v.kb[e.id] || { claims: {} }, claims = Object.values(r.claims);
        L.push(`| \`${e.id}\` | ${e.verified ? 'yes' : '**no**'} | ${e.family} | ${e.symptoms ? esc(e.symptoms.join(', ')) : 'all'} | ${e.sources.length} | ${claims.filter(c => c.found).length}/${claims.length} | ${e.beyond_sources ? 'yes' : 'no'} |`);
    }
    for (const e of entries) {
        const r = v.kb[e.id] || { claims: {}, sources_fetched: [] };
        L.push('', '---', '', `## \`${e.id}\``, '', `**${e.title}**`, '',
            `- Verified: **${e.verified ? 'yes' : 'no'}**${e.last_checked ? ` · last checked ${e.last_checked}` : ''}${e.reviewed ? ` · reviewed: ${e.reviewed.by} (${e.reviewed.date})` : ''}`,
            `- Family: ${e.family} · fires for symptoms: ${e.symptoms ? e.symptoms.join(', ') : 'all'}${e.requires_clue_types ? ` · needs one of these clues in the evidence: ${e.requires_clue_types.join(', ')}` : ''}`,
            `- When it fires: detector \`${e.detector}\` with \`${JSON.stringify(e.params)}\``, '',
            '**Claim**', '', `> ${quote(e.causes)}`, '', '**Change (the tool\'s recommendation)**', '', `> ${quote(e.change)}`, '');
        L.push('**Beyond the sources**', '', e.beyond_sources ? `> ${quote(e.beyond_sources)}` : '> Nothing is marked. (This means the author found no part of the claim that the cited pages do not state; it is still worth checking.)', '');
        L.push('**Sources**', '');
        for (const s of e.sources) { const p = v.pages[s.url] || {}; L.push(`- <${s.url}> — ${esc(s.title || '')} — HTTP ${p.status || 'not fetched'}${p.sha256 ? `, text sha256 \`${p.sha256.slice(0, 12)}…\`` : ''}${s.last_checked ? `, checked ${s.last_checked}` : ''}`); }
        L.push('', '**Claim phrases and the excerpt that contains each**', '');
        const rows = Object.entries(r.claims);
        if (!rows.length) L.push('_No claim phrases are recorded for this entry._');
        for (const [phrase, c] of rows) {
            L.push(`- [ ] \`${phrase}\` — ${c.found ? 'found' : '**NOT FOUND**'}${c.in && c.in.length ? ` in <${c.in[0]}>` : ''}`);
            if (c.excerpt) L.push(`  > …${quote(c.excerpt)}…`);
        }
        const missing = (e.claims_missing || []);
        if (missing.length) L.push('', `**Not found:** ${missing.map(m => `\`${m}\``).join(', ')}`);
    }

    // ---- appendix: taxonomy ----
    L.push('', '---', '', '## Appendix: feature taxonomy (`data/feature-taxonomy.json`)', '',
        'Hand-written map from the words a reporter uses to what code can show for that feature. A *row* in the "who provides this feature" table is only as trustworthy as the signals behind it, so a row whose signals are all unverified counts for less (see the scoring table printed with every investigation).', '',
        '| Feature | Verified | Signals found by content | Exist-only (slug is real) | Not found in the cited pages |', '|---|---|---|---|---|');
    for (const t of tax.entries) {
        const n = o => Object.values(o || {}).flat().length;
        L.push(`| \`${t.id}\` | ${t.verified ? 'yes' : '**no**'} | ${n(t.verified_signals)} | ${n(t.existence_only_signals)} | ${n(t.unverified_signals)} |`);
    }
    L.push('', '**Signals not found in the cited pages (these keep their row at reduced weight):**', '');
    for (const t of tax.entries) { const nf = Object.entries(t.unverified_signals || {}).map(([k, a]) => `${k}: ${a.map(x => `\`${x}\``).join(', ')}`); if (nf.length) L.push(`- **${t.id}** — ${nf.join(' · ')}`); }
    L.push('');
    // ---- exact settings (data/known-settings.json) ----
    const set = fs.existsSync(path.join(__dirname, '..', 'data', 'known-settings.json')) ? load('known-settings.json') : { entries: [] };
    L.push('---', '', '## Appendix: exact settings (`data/known-settings.json`)', '', 'Each setting lists what the admin screen calls it, the stored key (only when a primary source shows it), the plugin versions it was **read** in (not a promise for other versions) and every evidence phrase with the excerpt the verifier found. Read the excerpts: finding a phrase on a page is a check that the page says it, not proof the sentence in the entry is right.', '');
    for (const e of set.entries) {
        const r = (v.settings || {})[e.id];
        L.push(`### ${e.id} — ${esc(e.plugin.name)}: ${esc(e.label)}`, '', `- Verified: **${e.verified ? 'yes' : 'no'}**${e.last_checked ? `, checked ${e.last_checked}` : ''}`, `- Where: ${esc(e.admin_path)}`, `- Stored key: ${e.stored_key ? '`' + esc(e.stored_key) + '`' : '_none claimed_'} (${esc(e.stored_key_note)})`, `- Versions: ${esc(e.versions.verified_against)}${e.versions.range ? `; range min ${e.versions.range.min || '?'} max ${e.versions.range.max || 'open'}: ${esc(e.versions.range.meaning)}` : ''}`, `- Effect: ${esc(e.effect)}`, `- Change to try: ${esc(e.change)}`);
        for (const x of (r ? r.evidence : [])) L.push(`    - ${x.found ? 'FOUND' : 'MISSING'} (${x.role}) \`${esc(x.claim)}\` at ${x.url}${x.excerpt ? `: "${esc(quote(x.excerpt)).slice(0, 220)}"` : ''}`);
        L.push('');
    }
    return L.join('\n');
}

if (require.main === module) {
    const text = render();
    if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; if (cur !== text) { console.error('KNOWLEDGE-REVIEW.md is out of date: run  npm run guard:knowledge-review'); process.exit(1); } console.log('KNOWLEDGE-REVIEW.md is up to date'); }
    else { fs.writeFileSync(OUT, text); console.log(`Wrote ${OUT} (${text.split('\n').length} lines, ${load('known-conflicts.json').entries.length} entries)`); }
}
module.exports = { render, OUT };
